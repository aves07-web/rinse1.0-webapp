import { useState } from 'react';
import {
  BellRing,
  Calendar,
  CheckCircle2,
  ChevronLeft,
  ChevronRight,
  Copy,
  Download,
  Plus,
  RefreshCw,
  Trash2,
} from 'lucide-react';
import { ErpState, ScheduledTask } from '../types/erp';
import { DeleteConfirmationRequest } from './ConfirmDeleteModal';

interface TasksCalendarViewProps {
  state: ErpState;
  onAddTask: (task: Omit<ScheduledTask, 'id'>) => void;
  onToggleTaskStatus: (taskId: string) => void;
  onDeleteTask: (taskId: string) => void;
  onBulkDeleteTasks?: (taskIds: string[]) => void;
  onRequestDelete?: (req: DeleteConfirmationRequest) => void;
  onToggleRule: (ruleId: string) => void;
  onRunAutomatedScan: () => void;
  browserPermission: NotificationPermission | 'unsupported';
  onRequestBrowserPermission: () => void;
}

export function TasksCalendarView({
  state,
  onAddTask,
  onToggleTaskStatus,
  onDeleteTask,
  onBulkDeleteTasks,
  onRequestDelete,
  onToggleRule,
  onRunAutomatedScan,
  browserPermission,
  onRequestBrowserPermission,
}: TasksCalendarViewProps) {
  const [subTab, setSubTab] = useState<'calendar' | 'tasks' | 'sync'>('calendar');
  const [currentMonth, setCurrentMonth] = useState(() => {
    const d = new Date();
    return new Date(d.getFullYear(), d.getMonth(), 1);
  });
  const [selectedDateStr, setSelectedDateStr] = useState<string>(() => new Date().toISOString().slice(0, 10));
  const [copiedFeed, setCopiedFeed] = useState(false);
  const [selectedTaskIds, setSelectedTaskIds] = useState<string[]>([]);

  // New Task Form State
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [category, setCategory] = useState<ScheduledTask['category']>('Order Delivery');
  const [priority, setPriority] = useState<ScheduledTask['priority']>('High');
  const [dueDateTime, setDueDateTime] = useState(() => {
    const d = new Date(Date.now() + 3600 * 1000 * 3);
    return new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
  });
  const [reminderMinutesBefore, setReminderMinutesBefore] = useState(60);
  const [assignee, setAssignee] = useState('Owner');

  const feedUrl =
    typeof window !== 'undefined' ? `${window.location.origin}/api/calendar/feed.ics` : '/api/calendar/feed.ics';
  const jsonApiUrl =
    typeof window !== 'undefined' ? `${window.location.origin}/api/calendar/events` : '/api/calendar/events';

  const handleCreateTask = (e: React.FormEvent) => {
    e.preventDefault();
    if (!title.trim()) return;
    onAddTask({
      title: title.trim(),
      description: description.trim(),
      category,
      priority,
      status: 'Pending',
      dueAt: new Date(dueDateTime).toISOString(),
      reminderMinutesBefore,
      assignee,
      autoGenerated: false,
    });
    setTitle('');
    setDescription('');
  };

  const downloadTaskIcs = (task: ScheduledTask) => {
    const dtStart = new Date(task.dueAt).toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
    const dtEnd =
      new Date(new Date(task.dueAt).getTime() + 30 * 60000).toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
    const ics = [
      'BEGIN:VCALENDAR',
      'VERSION:2.0',
      'PRODID:-//Rinse//Task Event//EN',
      'BEGIN:VEVENT',
      `UID:${task.id}@rinse.local`,
      `DTSTAMP:${dtStart}`,
      `DTSTART:${dtStart}`,
      `DTEND:${dtEnd}`,
      `SUMMARY:${task.title}`,
      `DESCRIPTION:${task.description}`,
      'BEGIN:VALARM',
      'ACTION:DISPLAY',
      `DESCRIPTION:${task.title}`,
      `TRIGGER:-PT${task.reminderMinutesBefore}M`,
      'END:VALARM',
      'END:VEVENT',
      'END:VCALENDAR',
    ].join('\r\n');
    const blob = new Blob([ics], { type: 'text/calendar;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${task.id.toLowerCase()}.ics`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const copyFeedUrl = () => {
    navigator.clipboard.writeText(feedUrl);
    setCopiedFeed(true);
    setTimeout(() => setCopiedFeed(false), 2000);
  };

  // Calendar grid generation
  const year = currentMonth.getFullYear();
  const month = currentMonth.getMonth();
  const firstDayOfWeek = new Date(year, month, 1).getDay();
  const daysInMonth = new Date(year, month + 1, 0).getDate();

  const calendarCells: Array<{ dateStr: string; day: number } | null> = [];
  for (let i = 0; i < firstDayOfWeek; i++) calendarCells.push(null);
  for (let day = 1; day <= daysInMonth; day++) {
    const mm = String(month + 1).padStart(2, '0');
    const dd = String(day).padStart(2, '0');
    calendarCells.push({ dateStr: `${year}-${mm}-${dd}`, day });
  }

  // Combine scheduled tasks + order deadlines for calendar cells
  const getEventsForDate = (dateStr: string) => {
    const tasksOnDate = state.tasks.filter((t) => t.dueAt.slice(0, 10) === dateStr);
    const ordersOnDate = state.orders.filter(
      (o) => o.stage !== 'Delivered' && o.expectedDeliveryAt.slice(0, 10) === dateStr
    );
    return { tasksOnDate, ordersOnDate };
  };

  const selectedEvents = getEventsForDate(selectedDateStr);

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-end justify-between gap-4">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight text-slate-900">
            Task Management &amp; Calendar Automation
          </h1>
          <p className="text-sm text-slate-500 mt-1">
            Schedule washing batches, delivery deadlines, corporate cutoffs, and automated notifications
          </p>
        </div>

        <div className="flex items-center gap-1 p-1 bg-slate-200/70 rounded-xl self-start sm:self-auto">
          <button
            onClick={() => setSubTab('calendar')}
            className={`px-3.5 py-1.5 text-xs font-medium rounded-lg transition-colors whitespace-nowrap ${
              subTab === 'calendar' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Calendar Grid
          </button>
          <button
            onClick={() => setSubTab('tasks')}
            className={`px-3.5 py-1.5 text-xs font-medium rounded-lg transition-colors whitespace-nowrap ${
              subTab === 'tasks' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            All Tasks ({state.tasks.filter((t) => t.status !== 'Completed').length})
          </button>
          <button
            onClick={() => setSubTab('sync')}
            className={`px-3.5 py-1.5 text-xs font-medium rounded-lg transition-colors whitespace-nowrap ${
              subTab === 'sync' ? 'bg-white text-slate-900 shadow-xs' : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Calendar API &amp; Alerts
          </button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left 8 Columns: Active Tab View */}
        <div className="lg:col-span-8 space-y-6">
          {subTab === 'calendar' && (
            <div className="liquid-glass rounded-2xl p-6">
              <div className="flex items-center justify-between mb-5">
                <h2 className="text-base font-semibold text-slate-900">
                  {currentMonth.toLocaleString('en-US', { month: 'long', year: 'numeric' })}
                </h2>
                <div className="flex items-center gap-2">
                  <button
                    onClick={() => setCurrentMonth(new Date(year, month - 1, 1))}
                    className="p-2 rounded-xl bg-white/80 border border-slate-200 text-slate-700 hover:bg-white transition-colors"
                    aria-label="Previous month"
                  >
                    <ChevronLeft className="w-4 h-4" />
                  </button>
                  <button
                    onClick={() => {
                      const d = new Date();
                      setCurrentMonth(new Date(d.getFullYear(), d.getMonth(), 1));
                      setSelectedDateStr(d.toISOString().slice(0, 10));
                    }}
                    className="px-3 py-1.5 text-xs font-medium rounded-xl bg-white/80 border border-slate-200 text-slate-700 hover:bg-white transition-colors"
                  >
                    Today
                  </button>
                  <button
                    onClick={() => setCurrentMonth(new Date(year, month + 1, 1))}
                    className="p-2 rounded-xl bg-white/80 border border-slate-200 text-slate-700 hover:bg-white transition-colors"
                    aria-label="Next month"
                  >
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>
              </div>

              <div className="grid grid-cols-7 gap-1.5 text-center text-[11px] font-semibold text-slate-500 mb-2">
                {['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].map((d) => (
                  <div key={d} className="py-1">
                    {d}
                  </div>
                ))}
              </div>

              <div className="grid grid-cols-7 gap-1.5">
                {calendarCells.map((cell, idx) => {
                  if (!cell) {
                    return <div key={`empty-${idx}`} className="h-24 rounded-xl bg-white/25" />;
                  }
                  const { tasksOnDate, ordersOnDate } = getEventsForDate(cell.dateStr);
                  const isSelected = cell.dateStr === selectedDateStr;
                  const isToday = cell.dateStr === new Date().toISOString().slice(0, 10);
                  const totalEvents = tasksOnDate.length + ordersOnDate.length;

                  return (
                    <button
                      key={cell.dateStr}
                      onClick={() => setSelectedDateStr(cell.dateStr)}
                      className={`h-24 p-2 rounded-xl text-left flex flex-col justify-between transition-all border ${
                        isSelected
                          ? 'bg-white border-[#0071E3] shadow-sm'
                          : 'bg-white/60 border-slate-200/70 hover:bg-white/90'
                      }`}
                    >
                      <div className="flex items-center justify-between w-full">
                        <span
                          className={`text-xs font-mono tabular-nums font-semibold ${
                            isToday ? 'text-[#0071E3]' : 'text-slate-700'
                          }`}
                        >
                          {cell.day}
                        </span>
                        {totalEvents > 0 && (
                          <span className="text-[10px] font-mono text-slate-500 tabular-nums">
                            {totalEvents}
                          </span>
                        )}
                      </div>

                      <div className="space-y-1 overflow-hidden w-full">
                        {tasksOnDate.slice(0, 2).map((t) => (
                          <div
                            key={t.id}
                            className={`text-[10px] truncate font-medium ${
                              t.status === 'Completed'
                                ? 'text-slate-400 line-through'
                                : t.priority === 'Urgent'
                                ? 'text-red-600'
                                : 'text-[#0071E3]'
                            }`}
                          >
                            {t.title}
                          </div>
                        ))}
                        {ordersOnDate.slice(0, 1).map((o) => (
                          <div key={o.id} className="text-[10px] truncate text-emerald-700 font-medium">
                            Due: {o.id}
                          </div>
                        ))}
                      </div>
                    </button>
                  );
                })}
              </div>

              {/* Selected Date Breakdown */}
              <div className="mt-6 pt-5 border-t border-slate-200/70">
                <h3 className="text-sm font-semibold text-slate-900 mb-3">
                  Schedule for{' '}
                  <span className="font-mono tabular-nums">{selectedDateStr}</span>
                </h3>
                {selectedEvents.tasksOnDate.length === 0 && selectedEvents.ordersOnDate.length === 0 ? (
                  <p className="text-xs text-slate-500">No tasks or delivery deadlines scheduled for this date.</p>
                ) : (
                  <div className="space-y-2.5">
                    {selectedEvents.tasksOnDate.map((t) => (
                      <div
                        key={t.id}
                        className="flex items-center justify-between gap-3 p-3.5 rounded-xl bg-white/80 border border-slate-200/80"
                      >
                        <div className="min-w-0">
                          <div className="flex items-center gap-2 text-xs text-slate-500">
                            <span className="font-semibold text-slate-700">{t.category}</span>
                            <span>·</span>
                            <span>{t.priority}</span>
                            <span>·</span>
                            <span className="font-mono tabular-nums">
                              {new Date(t.dueAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                            </span>
                            <span>·</span>
                            <span>{t.assignee}</span>
                          </div>
                          <p
                            className={`text-sm font-medium mt-0.5 ${
                              t.status === 'Completed' ? 'line-through text-slate-400' : 'text-slate-900'
                            }`}
                          >
                            {t.title}
                          </p>
                        </div>
                        <div className="flex items-center gap-2 shrink-0">
                          <button
                            onClick={() => downloadTaskIcs(t)}
                            className="p-1.5 rounded-lg text-slate-500 hover:text-[#0071E3] hover:bg-slate-100 transition-colors"
                            title="Export .ics calendar event"
                          >
                            <Download className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => onToggleTaskStatus(t.id)}
                            className={`px-3 py-1.5 text-xs font-medium rounded-lg border transition-colors ${
                              t.status === 'Completed'
                                ? 'bg-emerald-50 border-emerald-200 text-emerald-700'
                                : 'bg-white border-slate-200 text-slate-700 hover:border-[#0071E3] hover:text-[#0071E3]'
                            }`}
                          >
                            {t.status === 'Completed' ? 'Done' : 'Mark Done'}
                          </button>
                        </div>
                      </div>
                    ))}
                    {selectedEvents.ordersOnDate.map((o) => (
                      <div
                        key={o.id}
                        className="flex items-center justify-between p-3.5 rounded-xl bg-white/70 border border-slate-200/70"
                      >
                        <div>
                          <div className="text-xs text-emerald-700 font-medium">
                            Retail Order Delivery Deadline · {o.deliveryOptionName}
                          </div>
                          <p className="text-sm font-medium text-slate-900 mt-0.5">
                            {o.id} — {o.customerName} ({o.stage})
                          </p>
                        </div>
                        <span className="text-xs font-mono text-slate-500 tabular-nums">
                          {new Date(o.expectedDeliveryAt).toLocaleTimeString([], {
                            hour: '2-digit',
                            minute: '2-digit',
                          })}
                        </span>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            </div>
          )}

          {subTab === 'tasks' && (
            <div className="liquid-glass rounded-2xl p-6">
              <div className="flex flex-wrap items-center justify-between gap-3 pb-4 border-b border-slate-200/70">
                <div className="flex items-center gap-3">
                  <h2 className="text-base font-semibold text-slate-900">Operational Task Queue</h2>
                  {state.tasks.length > 0 && (
                    <button
                      type="button"
                      onClick={() => {
                        if (selectedTaskIds.length === state.tasks.length) {
                          setSelectedTaskIds([]);
                        } else {
                          setSelectedTaskIds(state.tasks.map((t) => t.id));
                        }
                      }}
                      className="text-xs font-medium text-[#0071E3] hover:underline"
                    >
                      {selectedTaskIds.length === state.tasks.length ? 'Clear selection' : 'Select all'}
                    </button>
                  )}
                </div>
                <div className="flex items-center gap-2">
                  {selectedTaskIds.length > 0 && (
                    <button
                      type="button"
                      onClick={() => {
                        const doBulk = () => {
                          if (onBulkDeleteTasks) {
                            onBulkDeleteTasks(selectedTaskIds);
                          } else {
                            selectedTaskIds.forEach((id) => onDeleteTask(id));
                          }
                          setSelectedTaskIds([]);
                        };
                        if (onRequestDelete) {
                          onRequestDelete({
                            itemType: selectedTaskIds.length === 1 ? 'Scheduled Task' : 'Scheduled Tasks',
                            itemNameOrId:
                              selectedTaskIds.length === 1
                                ? state.tasks.find((t) => t.id === selectedTaskIds[0])?.title ||
                                  selectedTaskIds[0]
                                : `${selectedTaskIds.length} selected tasks`,
                            bulkCount: selectedTaskIds.length > 1 ? selectedTaskIds.length : undefined,
                            bodyText: `Permanently delete ${selectedTaskIds.length} scheduled task(s) from the task queue and calendar feed? This action cannot be undone.`,
                            onConfirmDelete: doBulk,
                          });
                        } else {
                          doBulk();
                        }
                      }}
                      className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg btn-danger"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                      Delete Selected ({selectedTaskIds.length})
                    </button>
                  )}
                  <a
                    href={feedUrl}
                    download="rinse-calendar.ics"
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-lg bg-white border border-slate-200 text-slate-700 hover:text-[#0071E3] transition-colors"
                  >
                    <Download className="w-3.5 h-3.5" />
                    Export All (.ics)
                  </a>
                </div>
              </div>

              <div className="divide-y divide-slate-200/60 mt-2">
                {state.tasks.map((t) => {
                  const isChecked = selectedTaskIds.includes(t.id);
                  return (
                    <div key={t.id} className="py-4 flex items-start justify-between gap-4">
                      <div className="flex items-start gap-3 min-w-0">
                        <input
                          type="checkbox"
                          checked={isChecked}
                          onChange={(e) => {
                            if (e.target.checked) {
                              setSelectedTaskIds((prev) => [...prev, t.id]);
                            } else {
                              setSelectedTaskIds((prev) => prev.filter((id) => id !== t.id));
                            }
                          }}
                          aria-label={`Select ${t.title}`}
                          className="mt-1 rounded border-slate-300 text-[#0071E3]"
                        />
                        <div className="min-w-0">
                          <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500">
                            <span
                              className={`font-semibold ${
                                t.priority === 'Urgent'
                                  ? 'text-red-600'
                                  : t.priority === 'High'
                                  ? 'text-amber-600'
                                  : 'text-slate-600'
                              }`}
                            >
                              {t.priority}
                            </span>
                            <span>·</span>
                            <span>{t.category}</span>
                            <span>·</span>
                            <span className="font-mono tabular-nums">
                              {new Date(t.dueAt).toLocaleString([], {
                                month: 'short',
                                day: 'numeric',
                                hour: '2-digit',
                                minute: '2-digit',
                              })}
                            </span>
                            <span>·</span>
                            <span>Assignee: {t.assignee}</span>
                            <span>·</span>
                            <span>Alert {t.reminderMinutesBefore}m prior</span>
                          </div>
                          <p
                            className={`text-sm font-semibold mt-1 ${
                              t.status === 'Completed' ? 'line-through text-slate-400' : 'text-slate-900'
                            }`}
                          >
                            {t.title}
                          </p>
                          {t.description && <p className="text-xs text-slate-600 mt-1">{t.description}</p>}
                        </div>
                      </div>

                      <div className="flex items-center gap-2 shrink-0">
                        <button
                          onClick={() => downloadTaskIcs(t)}
                          className="p-2 rounded-lg text-slate-500 hover:text-[#0071E3] hover:bg-white transition-colors"
                          title="Download .ics calendar invite"
                        >
                          <Calendar className="w-4 h-4" />
                        </button>
                        <button
                          onClick={() => onToggleTaskStatus(t.id)}
                          className={`inline-flex items-center gap-1 px-3 py-1.5 text-xs font-medium rounded-lg border transition-colors ${
                            t.status === 'Completed'
                              ? 'bg-emerald-50 border-emerald-200 text-emerald-700'
                              : 'bg-white border-slate-200 text-slate-700 hover:border-[#0071E3]'
                          }`}
                        >
                          <CheckCircle2 className="w-3.5 h-3.5" />
                          {t.status === 'Completed' ? 'Completed' : 'Complete'}
                        </button>
                        <button
                          type="button"
                          onClick={() => {
                            if (onRequestDelete) {
                              onRequestDelete({
                                itemType: 'Scheduled Task',
                                itemNameOrId: `${t.title} (${t.id})`,
                                bodyText: `Delete scheduled task "${t.title}" due ${new Date(t.dueAt).toLocaleString()}?`,
                                onConfirmDelete: () => {
                                  onDeleteTask(t.id);
                                  setSelectedTaskIds((prev) => prev.filter((id) => id !== t.id));
                                },
                              });
                            } else {
                              onDeleteTask(t.id);
                            }
                          }}
                          className="p-2 rounded-lg text-slate-400 hover:text-red-600 hover:bg-white transition-colors"
                          aria-label="Delete task"
                        >
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          )}

          {subTab === 'sync' && (
            <div className="space-y-6">
              <div className="liquid-glass rounded-2xl p-6 space-y-4">
                <div>
                  <h2 className="text-base font-semibold text-slate-900">
                    Standard Calendar APIs &amp; iCalendar (.ics) Feed
                  </h2>
                  <p className="text-xs text-slate-500 mt-1">
                    Subscribe from Apple Calendar, Outlook, Thunderbird, or local LAN workstations using the RFC 5545
                    feed or JSON REST endpoint. Works locally without internet dependency.
                  </p>
                </div>

                <div className="space-y-3">
                  <div className="p-3.5 rounded-xl bg-white/80 border border-slate-200/80">
                    <div className="flex items-center justify-between gap-2">
                      <span className="text-xs font-semibold text-slate-700">Live iCalendar Subscription URL (.ics)</span>
                      <div className="flex items-center gap-2">
                        <button
                          onClick={copyFeedUrl}
                          className="inline-flex items-center gap-1 text-xs font-medium text-[#0071E3] hover:underline"
                        >
                          <Copy className="w-3.5 h-3.5" />
                          {copiedFeed ? 'Copied' : 'Copy URL'}
                        </button>
                        <a
                          href={feedUrl}
                          download="rinse-calendar.ics"
                          className="inline-flex items-center gap-1 text-xs font-medium text-slate-700 hover:text-slate-900"
                        >
                          <Download className="w-3.5 h-3.5" />
                          Download
                        </a>
                      </div>
                    </div>
                    <p className="font-mono text-xs text-slate-600 mt-1.5 break-all">{feedUrl}</p>
                  </div>

                  <div className="p-3.5 rounded-xl bg-white/80 border border-slate-200/80">
                    <span className="text-xs font-semibold text-slate-700">REST Calendar Events Endpoint (GET / POST)</span>
                    <p className="font-mono text-xs text-slate-600 mt-1.5 break-all">{jsonApiUrl}</p>
                  </div>
                </div>
              </div>

              <div className="liquid-glass rounded-2xl p-6 space-y-4">
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <div>
                    <h2 className="text-base font-semibold text-slate-900">Automated Notification Engine</h2>
                    <p className="text-xs text-slate-500 mt-0.5">
                      Evaluates delivery deadlines, chemical thresholds, and corporate cutoffs automatically
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    {browserPermission !== 'granted' && browserPermission !== 'unsupported' && (
                      <button
                        onClick={onRequestBrowserPermission}
                        className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-lg bg-white border border-slate-200 text-slate-700 hover:bg-slate-50 transition-colors"
                      >
                        <BellRing className="w-3.5 h-3.5" />
                        Allow Desktop Alerts
                      </button>
                    )}
                    <button
                      onClick={onRunAutomatedScan}
                      className="inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-lg bg-[#0071E3] text-white hover:bg-[#0077ED] transition-colors"
                    >
                      <RefreshCw className="w-3.5 h-3.5" />
                      Run Automated Scan
                    </button>
                  </div>
                </div>

                <div className="divide-y divide-slate-200/60">
                  {state.notificationRules.map((rule) => (
                    <div key={rule.id} className="py-3 flex items-center justify-between gap-4">
                      <div>
                        <p className="text-sm font-medium text-slate-900">{rule.name}</p>
                        <p className="text-xs text-slate-500">
                          Trigger: {rule.triggerType} · Lead time: {rule.leadMinutes} min
                        </p>
                      </div>
                      <button
                        onClick={() => onToggleRule(rule.id)}
                        className={`px-3 py-1.5 text-xs font-medium rounded-lg transition-colors ${
                          rule.enabled
                            ? 'bg-[#0071E3] text-white'
                            : 'bg-slate-200 text-slate-600 hover:bg-slate-300'
                        }`}
                      >
                        {rule.enabled ? 'Active' : 'Disabled'}
                      </button>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          )}
        </div>

        {/* Right 4 Columns: Create Scheduled Task Form */}
        <div className="lg:col-span-4 liquid-glass rounded-2xl p-6">
          <h2 className="text-base font-semibold text-slate-900 pb-3 border-b border-slate-200/70">
            Schedule Operational Task
          </h2>
          <form onSubmit={handleCreateTask} className="space-y-4 mt-4">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Task Title</label>
              <input
                type="text"
                required
                value={title}
                onChange={(e) => setTitle(e.target.value)}
                placeholder="e.g., Inspect Hotel Regency Ironing Batch"
                className="w-full px-3 py-2 text-sm rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
              />
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Category</label>
                <select
                  value={category}
                  onChange={(e) => setCategory(e.target.value as ScheduledTask['category'])}
                  className="w-full px-3 py-2 text-xs rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
                >
                  <option value="Order Delivery">Order Delivery</option>
                  <option value="Washing Cycle">Washing Cycle</option>
                  <option value="Corporate Billing">Corporate Billing</option>
                  <option value="Inventory Alert">Inventory Alert</option>
                  <option value="Expense Due">Expense Due</option>
                  <option value="Payroll">Payroll</option>
                  <option value="General">General</option>
                </select>
              </div>
              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Priority</label>
                <select
                  value={priority}
                  onChange={(e) => setPriority(e.target.value as ScheduledTask['priority'])}
                  className="w-full px-3 py-2 text-xs rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
                >
                  <option value="Low">Low</option>
                  <option value="Normal">Normal</option>
                  <option value="High">High</option>
                  <option value="Urgent">Urgent</option>
                </select>
              </div>
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Due Date &amp; Time</label>
              <input
                type="datetime-local"
                required
                value={dueDateTime}
                onChange={(e) => setDueDateTime(e.target.value)}
                className="w-full px-3 py-2 text-xs font-mono rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
              />
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Assignee</label>
                <select
                  value={assignee}
                  onChange={(e) => setAssignee(e.target.value)}
                  className="w-full px-3 py-2 text-xs rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
                >
                  <option value="Owner">Owner</option>
                  {state.employees.map((emp) => (
                    <option key={emp.id} value={emp.name}>
                      {emp.name}
                    </option>
                  ))}
                </select>
              </div>
              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Notify Before (min)</label>
                <input
                  type="number"
                  min={0}
                  step={15}
                  value={reminderMinutesBefore}
                  onChange={(e) => setReminderMinutesBefore(Number(e.target.value))}
                  className="w-full px-3 py-2 text-xs font-mono rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
                />
              </div>
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Notes</label>
              <textarea
                rows={3}
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                placeholder="Instructions or batch references..."
                className="w-full px-3 py-2 text-xs rounded-xl bg-white/90 border border-slate-200 focus:outline-none focus:border-[#0071E3]"
              />
            </div>

            <button
              type="submit"
              className="w-full inline-flex items-center justify-center gap-1.5 px-4 py-2.5 text-xs font-semibold rounded-xl bg-[#0071E3] text-white hover:bg-[#0077ED] transition-colors"
            >
              <Plus className="w-4 h-4" />
              Add Task &amp; Sync Calendar
            </button>
          </form>
        </div>
      </div>
    </div>
  );
}
